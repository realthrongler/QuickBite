    public void refresh(){
        try{
            BufferedReader reader = new BufferedReader(new FileReader("src/orders.txt"));
                String line;
                while((line = reader.readLine()) != null){
                    String[] order = line.split(",");
                    int orderID = Integer.parseInt(order[0]);
                    int period = Integer.parseInt(order[1]);
                    int status = Integer.parseInt(order[2]);
                    double cost = Double.parseDouble(order[3]);
                    ArrayList<Item> items = new ArrayList<Item>();
                    for(int i = 4; i < order.length; i+=3){
                        String itemName = order[i];
                        int itemQuantity = Integer.parseInt(order[i+1]);
                        double itemCost = Double.parseDouble(order[i+2]);
                        
                        items.add(new Item(itemName, itemQuantity, itemCost));
                    }
                    
                    orders.add(new Order(orderID, period, status, cost, items));
                    
                }
        } catch (Exception e){
            //e.printStackTrace();
        }
        
        ArrayList <Integer> orderIDs = register.CurrentUser.getOrderIDsArrayList();
        
        String strOutput = "";
        for(int i = 0; i < orderIDs.size(); i++){
            int index = BinarySearch.binarySearch(orders, orderIDs.get(i), 0, orders.size());
            if(index >= 0){
                Order order = orders.get(index);
                ArrayList <Item> items = order.getItems();
                String strItems = "";
                for(int j = 0; j < items.size(); j++){
                    Item item = items.get(i);
                    strItems += "\n  x" + item.getQuantity() + " " + item.getName() + ", " + item.getCost();
                }
        
                strOutput += "Order ID : " + order.getOrderID() +
                             "\nPeriod : " + order.getPeriod() + 
                             "\nStatus : " + order.getStatusString() + 
                             "\nCost : " + order.getCost() + 
                             "\nItems : " + strItems + "\n\n";
            }
        }
        txt_orderDisplay.setText(strOutput);
    }

